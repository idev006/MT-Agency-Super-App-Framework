 assert.equal(r.status,'PENDING_APPROVAL');
 assert.equal(h.read('vc_campaigns')[0].submitted_count,1);
 assert.deepEqual(assertOk(assert,h.call('registrations.submit',payload),'replay same idempotency'),r);
