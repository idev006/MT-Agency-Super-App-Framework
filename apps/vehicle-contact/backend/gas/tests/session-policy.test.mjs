import assert from 'node:assert/strict';
import {authorizeSession,sessionExpiry,assertCampaignActive} from '../src/domain/policies/SessionPolicy.js';
const now='2026-11-17T12:00:00.000Z';
const session={user_id:'u1',status:'ACTIVE',issued_at:'2026-11-17T11:00:00.000Z',last_seen_at:'2026-11-17T11:55:00.000Z',expires_at:'2026-11-17T19:00:00.000Z',idle_timeout_minutes:30};
const user={user_id:'u1',status:'ACTIVE',password_change_required:false,permissions:['vehicle.lookup']};
assert.equal(authorizeSession(session,user,now,'vehicle.lookup').userId,'u1');
assert.throws(()=>authorizeSession(session,{...user,status:'SUSPENDED'},now,'vehicle.lookup'),/UNAUTHENTICATED/);
assert.throws(()=>authorizeSession({...session,revoked_at:now},user,now,'vehicle.lookup'),/REVOKED/);
assert.throws(()=>authorizeSession({...session,last_seen_at:'2026-11-17T11:30:00.000Z'},user,now,'vehicle.lookup'),/IDLE/);
assert.throws(()=>authorizeSession({...session,expires_at:now},user,now,'vehicle.lookup'),/EXPIRED/);
assert.throws(()=>authorizeSession(session,{...user,password_change_required:true},now,'vehicle.lookup'),/PASSWORD_CHANGE/);
assert.throws(()=>authorizeSession(session,user,now,'retention.delete.approve'),/FORBIDDEN/);
assert.equal(sessionExpiry(now,480),'2026-11-17T20:00:00.000Z');
const campaign={starts_at:'2026-11-17T00:00:00Z',ends_at:'2026-11-18T00:00:00Z',max_submissions:10,submitted_count:9};
assert.equal(assertCampaignActive(campaign,now),true);
assert.throws(()=>assertCampaignActive({...campaign,submitted_count:10},now),/QUOTA/);
assert.throws(()=>assertCampaignActive({...campaign,revoked_at:now},now),/REVOKED/);
console.log('Session and campaign policy assertions PASSED');
