import assert from 'node:assert/strict';
import {normalizePlate,vehicleBusinessKey,validateFivePhotos,assertVehicleTransition,assertApproval,canDeleteVehicle,assertSingleActiveQr} from '../src/domain/policies/VehicleLifecycle.js';
assert.equal(normalizePlate(' กข- 1234 '),'กข1234');
assert.equal(vehicleBusinessKey('กข 1234','TH-10'),'กข1234|TH-10');
assert.throws(()=>vehicleBusinessKey('กข',''),/province/);
assert.equal(validateFivePhotos(['FRONT','REAR','LEFT','RIGHT','FRONT_ANGLE'].map(slot=>({slot}))),true);
assert.equal(validateFivePhotos([{slot:'FRONT'}]),false);
assert.equal(validateFivePhotos(Array(5).fill({slot:'FRONT'})),false);
assert.equal(assertVehicleTransition('PENDING_APPROVAL','ACTIVE'),true);
assert.throws(()=>assertVehicleTransition('INACTIVE','ACTIVE'),/INVALID/);
assert.throws(()=>assertApproval([], {status:'PENDING_APPROVAL'}),/FORBIDDEN/);
assert.equal(assertApproval(['vehicle.registration.approve'],{status:'PENDING_APPROVAL'}),true);
const job={status:'DELETION_APPROVED',approved_by:'sysadmin-1',due_at:'2026-11-01T00:00:00Z'};
assert.deepEqual(canDeleteVehicle(job,[], '2026-11-17T00:00:00Z'),{allowed:false,reason:'FORBIDDEN'});
assert.deepEqual(canDeleteVehicle({...job,legal_hold:true},['retention.delete.approve'],'2026-11-17T00:00:00Z'),{allowed:false,reason:'LEGAL_HOLD'});
assert.deepEqual(canDeleteVehicle(job,['retention.delete.approve'],'2026-10-01T00:00:00Z'),{allowed:false,reason:'NOT_DUE'});
assert.deepEqual(canDeleteVehicle(job,['retention.delete.approve'],'2026-11-17T00:00:00Z'),{allowed:true});
assert.throws(()=>assertSingleActiveQr([{vehicle_id:'v1',status:'ACTIVE'},{vehicle_id:'v1',status:'ACTIVE'}],'v1'),/MULTIPLE/);
assert.equal(assertSingleActiveQr([{vehicle_id:'v1',status:'REVOKED'},{vehicle_id:'v1',status:'ACTIVE'}],'v1'),true);
console.log('Vehicle lifecycle policy assertions PASSED');
